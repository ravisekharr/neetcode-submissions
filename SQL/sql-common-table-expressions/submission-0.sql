WITH max_cte AS (
  SELECT customer_id,max(price) as price
  FROM orders
  GROUP BY customer_id
)
SELECT c.name as name
FROM customers c
JOIN max_cte m
ON c.id=m.customer_id
WHERE m.price<100
order by name

